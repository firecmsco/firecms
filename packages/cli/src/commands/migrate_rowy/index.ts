import fs from "fs";
import path from "path";
import chalk from "chalk";
import { convertRowyConfig, ConversionResult, ConvertedCollection } from "./convert";
import { getComments, toTs } from "./codegen";
import { getGcloudAccessToken, loadRowyConfigFromFirestore } from "./firestore_rest";
import { buildReport, findCredentials, MigrationTarget, scriptFileContent } from "./report";
import { RowyConfig } from "./types";

export type MigrateRowyOptions = {
    /** Firebase project to read Rowy's configuration from */
    projectId?: string;
    /** Or a JSON file with `{ settings, schemas, groupSchemas }` */
    inputFile?: string;
    outDir: string;
    target: MigrationTarget;
    /** Only convert these table ids */
    tables?: string[];
    /** Write into a folder that already has files */
    force?: boolean;
};

export async function migrateRowy(options: MigrateRowyOptions): Promise<ConversionResult> {
    const outDir = path.resolve(options.outDir);
    if (!options.force && fs.existsSync(outDir) && fs.readdirSync(outDir).length > 0) {
        throw new Error(`${outDir} already has files in it. Choose another folder with --out, or pass --force to overwrite.`);
    }

    let config: RowyConfig;
    let source: string;
    if (options.inputFile) {
        config = readConfigFile(options.inputFile);
        source = `the file \`${path.basename(options.inputFile)}\``;
    } else if (options.projectId) {
        console.log(`Reading Rowy's configuration from project ${chalk.bold(options.projectId)} (read only)...`);
        const token = await getGcloudAccessToken();
        config = await loadRowyConfigFromFirestore(options.projectId, token);
        source = `Firebase project \`${options.projectId}\``;
    } else {
        throw new Error("Pass --project with your Firebase project ID, or --input with a JSON file.");
    }

    const result = convertRowyConfig(config, { tables: options.tables });
    writeOutput(outDir, result, options.target, source);
    printSummary(outDir, result);
    return result;
}

export function readConfigFile(file: string): RowyConfig {
    const raw = JSON.parse(fs.readFileSync(file, "utf8"), reviveDates);
    if (!raw || typeof raw !== "object" || !raw.settings) {
        throw new Error(`${file} is not a Rowy configuration. Expected an object with \`settings\`, \`schemas\` and \`groupSchemas\`.`);
    }
    return {
        settings: raw.settings,
        schemas: raw.schemas ?? {},
        groupSchemas: raw.groupSchemas ?? {}
    };
}

/**
 * Dates written as `{ "__date": "2024-01-01T00:00:00.000Z" }` in an input file.
 */
function reviveDates(_key: string, value: any) {
    if (value && typeof value === "object" && Object.keys(value).length === 1 && typeof value.__date === "string") {
        return new Date(value.__date);
    }
    return value;
}

export function writeOutput(outDir: string, result: ConversionResult, target: MigrationTarget, source: string) {
    const collectionsDir = path.join(outDir, "collections");
    fs.mkdirSync(collectionsDir, { recursive: true });

    for (const collection of result.collections) {
        fs.writeFileSync(path.join(collectionsDir, `${collection.fileName}.ts`), collectionFileContent(collection, target, result));
    }
    fs.writeFileSync(path.join(collectionsDir, "index.ts"), indexFileContent(result.collections));

    for (const script of result.scripts) {
        const file = path.join(outDir, script.path);
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, scriptFileContent(script));
    }

    const credentials = findCredentials(result.scripts);
    fs.writeFileSync(path.join(outDir, "MIGRATION_REPORT.md"), buildReport({
        result,
        source,
        target,
        credentials,
        generatedAt: new Date()
    }));
}

export function collectionFileContent(collection: ConvertedCollection, target: MigrationTarget, result: ConversionResult): string {
    const importFrom = target === "cloud" ? "@firecms/cloud" : "@firecms/core";
    const todos = result.findings.filter(f =>
        f.level === "todo" && (f.tableId === collection.tableId || f.tableId.startsWith(`${collection.tableId}/`)));
    const header = [
        `// Generated by \`firecms migrate rowy\` from the Rowy table "${collection.tableName}" (${collection.tableId}).`,
        todos.length > 0
            ? `// MIGRATION_REPORT.md lists ${todos.length} to-do item${todos.length === 1 ? "" : "s"} for this table.`
            : "// MIGRATION_REPORT.md lists what to review for this table."
    ];
    const body = toTs(collection.collection);
    const comments = getComments(collection.collection).map(line => `// ${line}\n`).join("");
    return `${header.join("\n")}\nimport { buildCollection } from "${importFrom}";\n\n${comments}export const ${collection.variableName} = buildCollection(${body});\n`;
}

function indexFileContent(collections: ConvertedCollection[]) {
    const imports = collections.map(c => `import { ${c.variableName} } from "./${c.fileName}";`);
    return [
        "// Generated by `firecms migrate rowy`.",
        ...imports,
        "",
        "export const rowyCollections = [",
        ...collections.map((c, i) => `    ${c.variableName}${i < collections.length - 1 ? "," : ""}`),
        "];",
        ""
    ].join("\n");
}

function printSummary(outDir: string, result: ConversionResult) {
    const todos = result.findings.filter(f => f.level === "todo").length;
    const reviews = result.findings.filter(f => f.level === "review").length;
    const credentials = findCredentials(result.scripts);

    console.log("");
    console.log(`${chalk.green.bold("Done.")} Converted ${result.collections.length} table${result.collections.length === 1 ? "" : "s"} into ${chalk.bold(path.relative(process.cwd(), outDir) || ".")}`);
    console.log(`  ${todos} to do, ${reviews} to review, ${result.scripts.length} script${result.scripts.length === 1 ? "" : "s"} to port.`);
    for (const skipped of result.skippedTables) {
        console.log(`  ${chalk.yellow("Skipped")} ${skipped.id}: ${skipped.reason}`);
    }
    if (credentials.length > 0) {
        console.log("");
        console.log(`${chalk.red.bold("Warning:")} ${credentials.length === 1 ? "1 line" : `${credentials.length} lines`} in the copied Rowy scripts ${credentials.length === 1 ? "looks" : "look"} like a hardcoded key or password.`);
        console.log("  Treat each one as exposed and rotate it. Check the report before you commit the rowy-scripts folder.");
    }
    console.log("");
    console.log(`Next: read ${chalk.bold("MIGRATION_REPORT.md")}. Nothing in your project was changed.`);
}
