import { ConversionResult, Finding, ScriptFile } from "./convert";

export type MigrationTarget = "cloud" | "self-hosted";

export type CredentialWarning = {
    path: string;
    line: number;
    kind: string;
};

/**
 * Patterns that suggest a credential was pasted into a Rowy script.
 * Only the file and line are reported, never the match.
 */
const CREDENTIAL_PATTERNS: { kind: string, pattern: RegExp }[] = [
    { kind: "private key", pattern: /-----BEGIN [A-Z ]*PRIVATE KEY-----/ },
    { kind: "Stripe key", pattern: /\b[rs]k_(live|test)_[0-9A-Za-z]{10,}/ },
    { kind: "SendGrid key", pattern: /\bSG\.[\w-]{16,}\.[\w-]{16,}/ },
    { kind: "Slack token", pattern: /\bxox[abprs]-[0-9A-Za-z-]{10,}/ },
    { kind: "Google API key", pattern: /\bAIza[0-9A-Za-z_-]{35}\b/ },
    { kind: "GitHub token", pattern: /\bgh[pousr]_[0-9A-Za-z]{30,}/ },
    { kind: "AWS access key", pattern: /\bAKIA[0-9A-Z]{16}\b/ },
    { kind: "hardcoded secret", pattern: /(api[_-]?key|secret|token|password|passwd|auth)["']?\s*[:=]\s*["'`][^"'`\s]{12,}["'`]/i }
];

export function findCredentials(scripts: ScriptFile[]): CredentialWarning[] {
    const warnings: CredentialWarning[] = [];
    for (const script of scripts) {
        script.code.split("\n").forEach((line, index) => {
            const match = CREDENTIAL_PATTERNS.find(({ pattern }) => pattern.test(line));
            // +SCRIPT_HEADER_LINES: the line number in the written file, which starts with a header
            if (match) warnings.push({ path: script.path, line: index + 1 + SCRIPT_HEADER_LINES, kind: match.kind });
        });
    }
    return warnings;
}

export const SCRIPT_HEADER_LINES = 5;

export function scriptFileContent(script: ScriptFile) {
    const header = [
        "// @ts-nocheck",
        `// ${script.description}, table "${script.tableId}".`,
        "// Copied from Rowy as is by `firecms migrate rowy`. Nothing runs this file:",
        "// port it to a Cloud Function or a FireCMS callback, then delete it.",
        ""
    ];
    return header.join("\n") + "\n" + script.code.replace(/\s*$/, "") + "\n";
}

export function buildReport({
                                result,
                                source,
                                target,
                                credentials,
                                generatedAt
                            }: {
    result: ConversionResult,
    source: string,
    target: MigrationTarget,
    credentials: CredentialWarning[],
    generatedAt: Date
}): string {
    const lines: string[] = [];
    const push = (...l: string[]) => lines.push(...l);

    const todos = result.findings.filter(f => f.level === "todo");
    const reviews = result.findings.filter(f => f.level === "review");
    const columnCount = result.collections.reduce((sum, c) => sum + c.columns.length, 0);

    push(
        "# Rowy to FireCMS migration report",
        "",
        `Generated by \`firecms migrate rowy\` on ${generatedAt.toISOString().slice(0, 10)} from ${source}.`,
        `Target: ${target === "cloud" ? "FireCMS Cloud" : "self-hosted FireCMS"}.`,
        "",
        "This run only read Rowy's configuration under `_rowy_`. It changed nothing in Firestore or Google Cloud, and it did not read any documents.",
        "",
        "## Summary",
        "",
        "| Tables | Columns | To do | To review | Scripts to port | Extensions | Webhooks |",
        "|---|---|---|---|---|---|---|",
        `| ${result.collections.length} | ${columnCount} | ${todos.length} | ${reviews.length} | ${result.scripts.length} | ${result.extensions.length} | ${result.webhooks.length} |`,
        ""
    );

    if (credentials.length > 0) {
        push(
            "## Possible credentials in Rowy scripts",
            "",
            "These lines look like a key or password written into a script. The value is not shown here.",
            "Treat each one as exposed: rotate it, store the new one in Secret Manager, and read it from there in the ported code.",
            "Do not commit these script files until you have checked them.",
            "",
            ...credentials.map(c => `- \`${c.path}\`, line ${c.line}: looks like a ${c.kind}`),
            ""
        );
    }

    push("## Next steps", "", ...nextSteps(target), "");

    if (result.skippedTables.length > 0) {
        push("## Tables not converted", "", ...result.skippedTables.map(t => `- \`${t.id}\`: ${t.reason}`), "");
    }

    push("## Tables", "");
    for (const collection of result.collections) {
        push(
            `### ${collection.tableName} (\`${collection.tableId}\`)`,
            "",
            `File: \`collections/${collection.fileName}.ts\`, exported as \`${collection.variableName}\`.`,
            "",
            "| Column | Field | Rowy type | FireCMS |",
            "|---|---|---|---|",
            ...collection.columns.map(c => `| ${escapeCell(c.name)} | \`${c.fieldName}\` | ${c.rowyType} | ${escapeCell(c.firecms)} |`),
            ""
        );
        const findings = result.findings.filter(f => f.tableId === collection.tableId || f.tableId.startsWith(`${collection.tableId}/`));
        if (findings.length > 0) {
            push(...formatFindings(findings), "");
        }
    }

    if (result.roles.length > 0) {
        push(
            "## Roles",
            "",
            "Rowy kept roles in Firebase Auth custom claims (`roles`) and enforced data access in Firestore security rules.",
            "FireCMS keeps its own users and roles. Recreate these roles in FireCMS, then add your users to them.",
            "Your security rules still read the `roles` claim, so leave the claims in place until the rules no longer use them.",
            "",
            "| Rowy role | Suggested FireCMS role | Could see | Could change columns of |",
            "|---|---|---|---|",
            ...result.roles.map(r => `| \`${r.role}\` | ${suggestRole(r.role)} | ${listOrDash(r.visibleIn)} | ${listOrDash(r.modifies)} |`),
            ""
        );
    }

    if (result.extensions.length > 0) {
        push(
            "## Extensions",
            "",
            "These run inside the Cloud Function Rowy built for each table. They keep running until you delete that function.",
            "",
            "| Table | Extension | Type | Active | Triggers | Replace with |",
            "|---|---|---|---|---|---|",
            ...result.extensions.map(e => `| \`${e.tableId}\` | ${escapeCell(e.name)} | ${e.type} | ${e.active ? "yes" : "no"} | ${e.triggers.join(", ") || "-"} | ${escapeCell(e.replacement)} |`),
            ""
        );
    }

    if (result.webhooks.length > 0) {
        push(
            "## Webhooks",
            "",
            "These are served by Rowy's `rowy-hooks` Cloud Run service. Recreate each one as an HTTPS Cloud Function, then change the URL in the service that calls it.",
            "Verification secrets were not copied. Create new ones in Secret Manager.",
            "",
            "| Table | Webhook | Type | Active | Current URL | Had verification |",
            "|---|---|---|---|---|---|",
            ...result.webhooks.map(w => `| \`${w.tableId}\` | ${escapeCell(w.name)} | ${w.type} | ${w.active ? "yes" : "no"} | ${w.url ? `\`${w.url}\`` : "-"} | ${w.hasAuth ? "yes" : "no"} |`),
            ""
        );
    }

    if (result.scripts.length > 0) {
        push(
            "## Scripts copied from Rowy",
            "",
            "Each file holds code Rowy ran for you. None of it runs from here.",
            "",
            ...result.scripts.map(s => `- \`${s.path}\`: ${s.description}, table \`${s.tableId}\``),
            ""
        );
    }

    push(
        "## Files and images",
        "",
        "Rowy stored each file as `{ downloadURL, ref, name, type, lastModifiedTS }` in a list. The generated collections show these read-only.",
        "To upload from FireCMS, replace each stored list with the list of its `ref` values (the storage paths), then switch the property to the",
        "`storage` version written in the comment above it. The files themselves stay where they are in Cloud Storage.",
        ""
    );

    return lines.join("\n");
}

function nextSteps(target: MigrationTarget): string[] {
    const common = [
        "Read the to-do items under each table below. Columns marked read-only show their data but cannot be edited yet.",
        "Leave Rowy's Cloud Functions (`R-*`) and Rowy Run deployed until you have ported what they do. They keep running when you stop using Rowy's UI."
    ];
    if (target === "cloud") {
        return [
            "1. Create a FireCMS Cloud project for your Firebase project at https://app.firecms.co.",
            "2. Create the code project: `npx firecms init --cloud`, and pick that project when asked.",
            "3. Copy the `collections` folder into `src/`, and add `rowyCollections` to `collections` in `src/index.tsx`.",
            "4. Run `npm run dev` to check everything locally, then `npm run deploy` to publish.",
            ...common.map((step, i) => `${i + 5}. ${step}`)
        ];
    }
    return [
        "1. Create the app: `npx firecms init --community` (MIT), or `npx firecms init --pro` for user management, the schema editor and history.",
        "2. Copy the `collections` folder into `src/`, and add `rowyCollections` to the collections you pass to `useBuildNavigationController`.",
        "3. Run `npm run dev` and sign in with a Firebase user.",
        ...common.map((step, i) => `${i + 4}. ${step}`)
    ];
}

function formatFindings(findings: Finding[]): string[] {
    const order = { todo: 0, review: 1, info: 2 } as const;
    const label = { todo: "To do", review: "Review", info: "Note" } as const;
    return [...findings]
        .sort((a, b) => order[a.level] - order[b.level])
        .map(f => {
            const where = f.column ? `\`${f.column}\`: ` : "";
            const sub = f.tableId.includes("/") ? `(sub-table \`${f.tableId.split("/").slice(1).join("/")}\`) ` : "";
            return `- **${label[f.level]}** ${sub}${where}${f.message}`;
        });
}

function suggestRole(role: string) {
    const upper = role.toUpperCase();
    if (upper === "ADMIN" || upper === "OWNER") return "Admin";
    if (upper.includes("VIEW") || upper.includes("READ")) return "Read-only access to the tables it could see";
    return "Access to the tables it could see";
}

function listOrDash(values: string[]) {
    return values.length > 0 ? values.map(v => `\`${v}\``).join(", ") : "-";
}

function escapeCell(text: string) {
    return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}
